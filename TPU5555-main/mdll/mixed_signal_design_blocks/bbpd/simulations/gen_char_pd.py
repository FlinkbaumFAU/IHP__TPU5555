#!/usr/bin/env python3
"""Generate the phase-comparator characterisation deck (char_pd.spice).

What this measures
------------------
The comparator in src/pd.sch is supposed to report the SIGN of (t_div -
t_clk_ref) with no dead zone. Two things have to be true for the MDLL loop to
work, and neither is obvious from the schematic:

  1. POLARITY. comp must be 0 when div leads and 1 when div lags. The loop
     filter's direction (rtl/dlf.v) is keyed to that mapping, and getting it
     backwards turns negative feedback into positive feedback.

  2. STATIC OFFSET. The crossing point -- the delay at which comp flips -- is
     not at dt = 0. A D flip-flop needs setup time, and clk_ref arrives as a
     ramp rather than a settled level, so the effective sampling instant sits
     some tens of picoseconds off the clk_ref edge. Whatever that offset is,
     the loop will drive the MDLL to it: it IS the residual phase error at
     lock. This deck is how we find out how big it is.

Method
------
One transient, N independent copies of pd, each with its own div source at a
different delay. The comparator is three cells, so sweeping by replication
costs almost nothing and avoids N ngspice invocations -- unlike the DCO sweep
in gen_char_dco.py, which has to shard across cores.

The pd subckt is taken from the xschem export rather than hand-written here, so
the deck cannot drift away from the schematic. xschem comments out the
.subckt/.ends of a TOP-LEVEL netlist (it assumes you want a runnable deck), so
those two lines get uncommented on the way in.

Timing, with T_REF = 10 ns:

    clk_ref  rising edges at 0, 10, 20, 30 ns
    div_i    rising edges at 10 and 20 ns + dt_i, period T_REF
    x1       samples clk_ref at 20 ns + dt_i
    x2       retimes ~0.4 ns after each clk_ref edge (pd.sch x7). For dt_i
             beyond ~0.2 ns that is before x1's sample, so x2 picks it up one
             period later -- the same value, div repeats with the same dt_i.

comp is sampled twice, in two different reference cycles, to catch anything
that only settles on the second one.
"""

import argparse
import os
import re

PDK  = os.environ.get("PDK_ROOT", "/opt/IHP-Open-PDK/").rstrip("/") + "/ihp-sg13g2"
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

T_REF   = 10e-9
CT      = 20e-12      # source rise/fall (overridable: --ct)
T_EDGE  = 20e-9       # the clk_ref edge under test
T_MEAS  = (29e-9, 39e-9)

# Coarse points establish that the sign is a clean step over a wide range;
# the fine grid locates the crossing.
COARSE = [-3e-9, -2e-9, -1e-9, -500e-12, -300e-12,
          300e-12, 500e-12, 1e-9, 2e-9, 3e-9]
FINE   = [i * 10e-12 for i in range(-20, 21)]


def deltas(fine=None):
    return sorted(set(COARSE + (FINE if fine is None else fine)))


def pd_subckt():
    """The pd subcircuit, straight out of the xschem SPICE export."""
    path = os.path.join(ROOT, "build", "01-synth", "pd.spice")
    if not os.path.exists(path):
        raise SystemExit(f"missing {path} -- run `make build/01-synth/pd.spice`")

    out, keep = [], False
    for line in open(path):
        s = line.rstrip("\n")
        if s.startswith("**.subckt pd "):
            keep, s = True, s[2:]
        elif s.startswith("**.ends") and keep:
            out.append(".ends")
            break
        elif s.startswith("*"):
            continue
        if keep:
            out.append(s)
    if not out:
        raise SystemExit("could not find the pd subckt in the xschem export")
    return out


def build(ct=CT, fine=None):
    dts = deltas(fine)

    L = [
        "** Phase-comparator characterisation: comp vs. div-to-clk_ref delay.",
        "**",
        "** Generated by simulations/gen_char_pd.py -- do not edit by hand.",
        "",
        f".LIB {PDK}/libs.tech/ngspice/models/cornerMOSlv.lib mos_tt",
        ".OPTIONS KLU",
        f".INCLUDE {PDK}/libs.ref/sg13g2_stdcell/spice/sg13g2_stdcell.spice",
        ".PARAM VDD=1.2",
        ".TEMP 27",
        "",
        "* The sg13g2 cells take VDD/VSS as ordinary subckt pins and the xschem",
        "* export passes them positionally, so they have to be global or every",
        "* copy of pd would float. Same convention as clk_gen's char deck.",
        ".GLOBAL VSS",
        ".GLOBAL VDD",
        "",
        "* ---- pd, from the xschem export of src/pd.sch ----",
    ]
    L += pd_subckt()
    L += [
        "",
        "VVDD VDD 0 DC {VDD}",
        "VVSS VSS 0 0",
        "",
        "* Reference clock and reset are shared by every copy.",
        f"Vref clk_ref 0 PULSE(0 {{VDD}} 0 {ct:g} {ct:g} {T_REF/2:g} {T_REF:g})",
        f"Vrst resetb 0 PWL(0 0 1n 0 {{1n+{ct:g}}} {{VDD}})",
        "",
        "* One copy per delay point. div is a 1-in-4 pulse like the real",
        "* divider output; only its RISING edge matters to the comparator.",
    ]
    for i, dt in enumerate(dts):
        # one period early: x2 retimes ~0.4 ns after clk_ref, so a decision
        # taken later than that reaches comp a period later
        t0 = T_EDGE + dt - T_REF
        L.append(f"Vdiv{i} div{i} 0 PULSE(0 {{VDD}} {t0:g} {ct:g} {ct:g} "
                 f"{T_REF/4:g} {T_REF:g})")
        L.append(f"xpd{i} clk_ref div{i} resetb comp{i} ckd{i} cku{i} pd")
    L += ["", ".control", "  set filetype=ascii", "  tran 2p 45n"]
    for i in range(len(dts)):
        for j, tm in enumerate(T_MEAS):
            L.append(f"  meas tran m{j}_{i} FIND v(comp{i}) AT={tm:g}")
    L += ["  quit", ".endc", ".end", ""]
    return "\n".join(L), dts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", default=os.path.join(ROOT, "build", "char_pd.spice"))
    ap.add_argument("--ct", type=float, default=CT * 1e12,
                    help="source rise/fall in ps (default 20). The measured "
                         "offset is partly slew-dependent, so this is how you "
                         "separate the flop's setup time from the ramp.")
    ap.add_argument("--fine-ps", nargs=3, type=float, metavar=("LO", "HI", "STEP"),
                    help="override the fine grid, in ps")
    args = ap.parse_args()

    fine = None
    if args.fine_ps:
        lo, hi, st = args.fine_ps
        n = int(round((hi - lo) / st))
        fine = [(lo + k * st) * 1e-12 for k in range(n + 1)]

    text, dts = build(ct=args.ct * 1e-12, fine=fine)
    os.makedirs(os.path.dirname(args.o), exist_ok=True)
    open(args.o, "w").write(text)
    print(f"wrote {args.o}: {len(dts)} delay points "
          f"({dts[0]*1e12:.0f} ps .. {dts[-1]*1e12:.0f} ps)")


if __name__ == "__main__":
    main()
