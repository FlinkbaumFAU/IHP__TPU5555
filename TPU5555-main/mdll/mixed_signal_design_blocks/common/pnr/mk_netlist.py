#!/usr/bin/env python3
"""Assemble the gate-level netlist LibreLane places and routes.

Shared by every schematic-first block (clk_gen, bbpd, tdc). Each block used to
carry its own near-identical copy differing only in the module list.

xschem expands sg13g2 cells all the way to transistors (sg13_lv_nmos/pmos), so
its Verilog export cannot be handed to a digital flow as-is -- those module
bodies must go, leaving the cells as references the Liberty/LEF provide.
Custom cells (custom_cap_*) are only ever instantiated, never defined, so they
are already clean blackboxes.

Output = the design hierarchy (--keep) + pre-synthesised RTL blocks (--append,
each a mapped netlist that the block's synth/lec_*.tcl proved equivalent to its
RTL). The whole netlist therefore reaches LibreLane already mapped, and the
flow runs with SYNTH_ELABORATE_ONLY. That matters for every block here: rings
are deliberate combinational loops, clk_gen's delay_cell is a latch, and the
phase detectors are hand-picked flops operated metastable on purpose -- a
re-synthesis is free to "simplify" or resize all of them.

Example (tdc/Makefile):
    mk_netlist.py --top tdc --keep tdc tdc_pd edge_lock_dector slow_osci fast_osci \\
                  --nl build/01-synth/tdc.nl.v --append build/01-synth/counter.v \\
                  --out build/01-synth/tdc.pnr.v
"""

import argparse
import os
import re
import sys


def modules(path):
    """Split a verilog file into {name: text} by module."""
    src = open(path).read()
    out = {}
    for m in re.finditer(r"^module\s+(\w+)\s*(.*?)^endmodule", src, re.S | re.M):
        out[m.group(1)] = m.group(0)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--top", required=True, help="top module (for the report)")
    ap.add_argument("--keep", nargs="+", required=True,
                    help="modules of the xschem export to keep, top first")
    ap.add_argument("--nl", required=True, help="xschem Verilog export")
    ap.add_argument("--append", nargs="*", default=[],
                    help="pre-synthesised gate netlists; every module is appended")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    top = modules(a.nl)
    missing = [k for k in a.keep if k not in top]
    if missing:
        sys.exit(f"ERROR: missing modules in xschem export: {missing}")
    if a.keep[0] != a.top:
        sys.exit(f"ERROR: --keep must start with the top module {a.top}")

    appended = {}
    for path in a.append:
        mods = modules(path)
        if not mods:
            sys.exit(f"ERROR: no modules in {path} -- has its synthesis run?")
        appended.update(mods)

    # --- guard: no undriven power wires ------------------------------------
    # vdd.sym/gnd.sym resolve against the global rails in SPICE, but in Verilog
    # they netlist as plain wires with no driver -- X nets that yosys reports as
    # "used but has no driver" and that survive all the way to a confusing LVS
    # result. A schematic that needs a hard 0/1 must instantiate a real
    # sg13g2_tiehi/tielo (clk_gen's selector and tdc's reset generator do).
    undriven = []
    for mod in a.keep:
        for net in ("VDD", "GND", "VSS"):
            if f"wire {net} ;" not in top[mod]:
                continue
            driven = re.search(rf"\.(Y|X|Q|Z|L_HI|L_LO)\(\s*{net}\s*\)", top[mod])
            if not driven:
                undriven.append(f"{mod}.{net}")
    if undriven:
        sys.exit("ERROR: undriven power wire(s) in the xschem export: "
                 + ", ".join(undriven)
                 + "\n  A schematic is using vdd.sym/gnd.sym where it needs a real"
                 + "\n  sg13g2_tiehi/sg13g2_tielo instance.")

    dropped = sorted(set(top) - set(a.keep))
    body = [top[k] for k in a.keep] + list(appended.values())
    text = ("// Generated by common/pnr/mk_netlist.py -- do not edit.\n"
            f"// Design hierarchy from xschem + synthesised {', '.join(appended) or 'nothing'}.\n"
            f"// Dropped transistor-level cell bodies: {', '.join(dropped)}\n\n"
            + "\n\n".join(body) + "\n")

    # Nothing transistor-level may survive, or the flow will try to place devices.
    for tok in ("sg13_lv_nmos", "sg13_lv_pmos"):
        if tok in text:
            sys.exit(f"ERROR: {tok} still present in the P&R netlist")

    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, "w").write(text)

    customs = sorted(set(re.findall(r"^\s*(custom_\w+)\s", text, re.M)))
    print(f"wrote {a.out}")
    print(f"  kept    : {', '.join(a.keep)} + {', '.join(appended) or '-'}")
    print(f"  dropped : {len(dropped)} transistor-level cell bodies")
    for c in customs:
        n = len(re.findall(rf"^\s*{c}\s", text, re.M))
        print(f"  {c} instances: {n}")


if __name__ == "__main__":
    main()
