#!/usr/bin/env python3
"""Generate the DCO characterisation sweep deck (char_dco.spice).

The decoder is deliberately NOT in the SPICE path: it is combinational and
already proven equivalent to its RTL by SAT (synth/lec_decode.tcl), so
modelling it here would add runtime without adding confidence. Driving the 63
thermometer nodes directly is also what makes a full 64-code sweep cheap.

The thermometer-index mapping below is the same formula dco_decode.v uses, kept
here rather than hand-transcribed so the two cannot drift apart silently.

A run takes ~30-60 s per code, so run_char.sh shards the code range across
cores and merges the results; --lo/--hi/--csv exist for that.
"""

import argparse
import os

PDK    = os.environ.get("PDK_ROOT", "/opt/IHP-Open-PDK/").rstrip("/") + "/ihp-sg13g2"
CUST   = os.environ.get("CUSTOM_STDCELL",
                        os.path.expanduser("~/Documents/Passionate/custom_stdcell"))
NTHERM = 63
HERE   = os.path.dirname(os.path.abspath(__file__))


def tidx(c, s, p):
    """Thermometer index for cell c, side s (0=co/out, 1=cob/outb), slot p."""
    return 8 * p + 2 * c + s


def node(c, s, p):
    i = tidx(c, s, p)
    return f"t{i}" if i < NTHERM else "VSS"   # slot 63 has no bit -> tied low


def build(lo=0, hi=63, csv="dco_char.csv"):
    L = [
        "** DCO characterisation: oscillation frequency vs. 6-bit thermometer code.",
        "**",
        "** Generated by simulations/gen_char_dco.py -- do not edit by hand.",
        "** The cap bank is 63 identical custom_cap_8 units; enabled-unit count equals",
        "** the code exactly, so the period must rise monotonically with the code.",
        "",
        f".LIB {PDK}/libs.tech/ngspice/models/cornerMOSlv.lib mos_tt",
        ".OPTIONS KLU",
        f".INCLUDE {PDK}/libs.ref/sg13g2_stdcell/spice/sg13g2_stdcell.spice",
        f".INCLUDE {CUST}/custom_stdcell.spice",
        ".PARAM VDD=1.2",
        ".TEMP 27",
        "",
        "* ---- delay_cell, mirroring the xschem export of src/delay_cell.sch ----",
    ]

    co  = " ".join(f"co[{p}]"  for p in range(7, -1, -1))
    cob = " ".join(f"cob[{p}]" for p in range(7, -1, -1))
    L.append(f".subckt delay_cell in out {co} {cob} outb inb")
    # inv_2 forward inverters and cap_8 units (2026-10-30, were inv_1 / cap_4):
    # the extracted ring-node wiring (~6.3 fF each) made code 0 too slow at ss.
    # See TAPEOUT.md, "DCO range at the slow corner".
    L += ["x13 out in VDD VSS sg13g2_inv_2",
          "x14 outb inb VDD VSS sg13g2_inv_2",
          "x11 out outb VDD VSS sg13g2_inv_1",
          "x12 outb out VDD VSS sg13g2_inv_1"]
    L += [f"xco{p} co[{p}] out VDD VSS custom_cap_8" for p in range(8)]
    L += [f"xcob{p} cob[{p}] outb VDD VSS custom_cap_8" for p in range(8)]
    L += [".ends", ""]

    L.append("* ---- ring: 4 delay cells + injection mux ----")
    ring = [("x3", "net8", "net7", "net6", "net9"),
            ("x4", "net7", "net5", "net1", "net6"),
            ("x5", "net5", "net2", "net4", "net1"),
            ("x6", "net2", "ring_p", "ring_n", "net4")]
    for c, (inst, i_, o_, ob_, ib_) in enumerate(ring):
        cc = " ".join(node(c, 0, p) for p in range(7, -1, -1))
        cb = " ".join(node(c, 1, p) for p in range(7, -1, -1))
        L.append(f"{inst} {i_} {o_} {cc} {cb} {ob_} {ib_} delay_cell")

    # The loop closes straight from the ring nodes -- the output buffers are NOT
    # in it. The mux feed is CROSSED (x9 <- ring_p, x1 <- ring_n) and that is
    # load-bearing: ring_p/ring_n are complementary, so feeding ring_p where
    # inv(ring_n) used to go keeps polarity AND keeps loop parity odd. Uncrossing
    # it removes one inversion and the ring does not oscillate at all (measured:
    # every code returns FAIL). Do not "tidy" this.
    L += ["x7 net8 M_outb VDD VSS sg13g2_inv_2",
          "x8 net9 M_out VDD VSS sg13g2_inv_2",
          "x9 M_outb ring_p clk_ref sel VDD VSS sg13g2_mux2_2",
          "x1 M_out ring_n clk_refb sel VDD VSS sg13g2_mux2_2",
          ""]

    # Output taps, outside the loop and tapered 1 -> 4 -> 16 so each ring node
    # sees only an inv_1 gate. Feeding inv_16 directly off the ring node costs
    # ~23% of f_max, because the delay cell's inv_1 then drives the mux input
    # and that large gate together.
    L += ["xb1 tb1 ring_p VDD VSS sg13g2_inv_1",
          "xb2 tb2 tb1 VDD VSS sg13g2_inv_4",
          "x2 clk_outb tb2 VDD VSS sg13g2_inv_16",
          "xb3 tb3 ring_n VDD VSS sg13g2_inv_1",
          "xb4 tb4 tb3 VDD VSS sg13g2_inv_4",
          "x10 clk_out tb4 VDD VSS sg13g2_inv_16",
          ""]

    L += ["VVDD VDD 0 DC {VDD}",
          "VVSS VSS 0 0",
          "Vsel sel 0 0          $ free-running: mux selects the ring, not clk_ref",
          "Vref clk_ref 0 0",
          "Vrefb clk_refb 0 {VDD}",
          "",
          "* One swept control voltage; each thermometer node derives from it, so",
          "* the loop alters a single source instead of 63.",
          "Vcode code 0 DC 0"]
    L += [f"Bt{i} t{i} 0 V = (v(code) > {i}.5) ? {{VDD}} : 0" for i in range(NTHERM)]

    # 220 ns / 25 ns settle leaves room for 15 rising edges down to ~77 MHz,
    # comfortably past the ~200 MHz expected at full scale.
    L += ["",
          ".ic v(M_out)=0 v(M_outb)=1.2",
          ".save v(M_out)",
          "",
          ".control",
          "set noaskquit",
          # one OSDI thread per deck: run_char.sh already runs one deck per
          # core, and ngspice would otherwise start a thread per core in each
          "set num_threads=1",
          "set filetype=ascii",
          'echo code freq > ' + csv,
          f"let code = {lo}",
          f"while code <= {hi}",
          "  alter Vcode = code",
          "  tran 20p 220n uic",
          "  meas tran ta when v(M_out)=0.6 rise=5 td=25n",
          "  meas tran tb when v(M_out)=0.6 rise=15 td=25n",
          "  if length(ta) > 0",
          "    let fr = 10/(tb-ta)",
          '    echo "$&code $&fr" >> ' + csv,
          "  else",
          '    echo "$&code FAIL" >> ' + csv,
          "  end",
          "  destroy all",
          "  let code = code + 1",
          "end",
          "quit",
          ".endc",
          "",
          ".GLOBAL VSS",
          ".GLOBAL VDD",
          ".end"]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lo", type=int, default=0, help="first code (inclusive)")
    ap.add_argument("--hi", type=int, default=63, help="last code (inclusive)")
    ap.add_argument("--csv", default="dco_char.csv", help="csv the deck writes")
    ap.add_argument("-o", "--out", default=os.path.join(HERE, "char_dco.spice"))
    a = ap.parse_args()

    # Every thermometer bit must land in exactly one slot, and exactly one slot
    # (cell 3, cob, slot 7) must be the tie-off.
    from collections import Counter
    used = Counter(node(c, s, p) for c in range(4) for s in range(2) for p in range(8))
    assert used["VSS"] == 1, f"expected 1 tied slot, got {used['VSS']}"
    assert all(used[f"t{i}"] == 1 for i in range(NTHERM)), "thermometer bit reused"

    with open(a.out, "w") as f:
        f.write(build(a.lo, a.hi, a.csv))
    print(f"wrote {a.out} (codes {a.lo}..{a.hi}, {NTHERM} bits, 1 slot tied low)")
