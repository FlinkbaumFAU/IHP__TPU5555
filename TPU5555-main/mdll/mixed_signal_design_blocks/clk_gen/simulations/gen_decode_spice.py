#!/usr/bin/env python3
"""Emit a behavioural SPICE subckt for dco_decode.

src/dco.sch instantiates dco_decode, so any SPICE netlist of dco.sch or
test_clk_gen.sch needs a subckt for it. Yosys' SPICE backend cannot supply one:
it writes a flat netlist with no .subckt wrapper, dotted net names, and cell
instances missing VDD/VSS (the PDK's sg13g2_inv_1 is "Y A VDD VSS").

A behavioural model is the right fidelity here anyway. The decoder is
combinational and already proven equivalent to its RTL by SAT
(synth/lec_decode.tcl). Its gate delay is omitted: the code itself changes
once per reference cycle, and the dither's frac_on (unit N on for the last
code[1:0] periods of a run) switches a fixed ~0.3..0.5 ns after DCO edges in
the gates, so the window of extra capacitance only shifts, by the same amount
at both ends. Carrying the gates through a PLL transient would cost runtime and
buy little. The gate-level
netlist still exists in build/01-synth/dco_decode.v for P&R.

Port order matches what xschem emits for src/dco_decode.sym, and the slot
mapping is imported from gen_char_dco.py so the two cannot drift apart.
"""

import argparse
import os

from gen_char_dco import NTHERM, tidx          # single source of truth

HERE  = os.path.dirname(os.path.abspath(__file__))
NSKIP = 2     # loop filter is 8-bit, DCO resolves the top 6


def ports():
    """code[7]..code[0], g[1], g[0], then co0,cob0,co1,cob1,... each [7]..[0]."""
    p = [f"code[{b}]" for b in range(7, -1, -1)] + ["g[1]", "g[0]"]
    for c in range(4):
        for s in ("co", "cob"):
            p += [f"{s}{c}[{b}]" for b in range(7, -1, -1)]
    return p


def build():
    L = [
        "** Behavioural model of dco_decode (6-bit binary -> 63 thermometer, plus",
        "** the dither: unit N for the last code[1:0] periods of a run, from the",
        "** divider's Gray period count g[1:0]).",
        "** Generated by simulations/gen_decode_spice.py -- do not edit by hand.",
        "** Logic is SAT-proven against the RTL; gate delay is omitted deliberately.",
        "",
        f".subckt dco_decode {' '.join(ports())} params: vhi=1.2 vth=0.6",
        "",
        f"* Decoded value of code[7:{NSKIP}] as a voltage on an internal node.",
    ]
    terms = " + ".join(
        f"(v(code[{NSKIP + b}]) > vth) * {1 << b}" for b in range(5, -1, -1))
    L.append(f"Bnsum nsum 0 V = {terms}")
    L += ["",
          "* frac_on: this period is one of the last k = code[1:0] of the run.",
          "* g = 00 01 11 10 in periods 0..3: k=1 -> g1&~g0, k=2 -> g1, k=3 -> g1|g0.",
          "Bk kk 0 V = (v(code[1]) > vth) * 2 + (v(code[0]) > vth)",
          "Bg1 gg1 0 V = (v(g[1]) > vth)",
          "Bg0 gg0 0 V = (v(g[0]) > vth)",
          "Bfr fr 0 V = (abs(v(kk) - 1) < 0.5) * v(gg1) * (1 - v(gg0))"
          " + (abs(v(kk) - 2) < 0.5) * v(gg1)"
          " + (abs(v(kk) - 3) < 0.5) * (1 - (1 - v(gg1)) * (1 - v(gg0)))",
          "",
          "* Unit i is on below N, and unit N while frac_on: N + frac_on > i."]
    L.append("* One unit cap per thermometer bit; slot 63 has no bit and ties low.")

    for c in range(4):
        for s, sig in ((0, "co"), (1, "cob")):
            for p in range(7, -1, -1):
                i = tidx(c, s, p)
                net = f"{sig}{c}[{p}]"
                if i < NTHERM:
                    L.append(f"B{sig}{c}_{p} {net} 0 V = (v(nsum) + v(fr) > {i}.5) ? vhi : 0")
                else:
                    L.append(f"B{sig}{c}_{p} {net} 0 V = 0   $ slot {i}: tied low")
    L += ["", ".ends", ""]
    return "\n".join(L)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("-o", "--out", default=os.path.join(HERE, "dco_decode.spice"))
    a = ap.parse_args()
    with open(a.out, "w") as f:
        f.write(build())
    print(f"wrote {a.out} ({NTHERM} decoded bits + 1 tied slot)")
