#!/usr/bin/env python3
"""Write slow_osci.sch and fast_osci.sch -- the TDC's matched Vernier rings.

Both rings are generated from this one description so they cannot drift apart:
the same NAND + 6x buf_1 loop, the same eight custom_cap_4 on the last node, the
same output buffer, the same pair of tie cells. The ONLY difference is which tie
cell each cap's A pin is wired to:

    A = 1 (tiehi) -> cap switched to its small value -> faster
    A = 0 (tielo) -> cap switched to its large value -> slower

Fast ring: 8 caps high.  Slow ring: 2 high, 6 low.  Measured standalone
(1.2 V, tt): T_fast = 1045 ps, one cap unit = 3.02 ps, so dT = 6 units =
18.1 ps. The unit tracks the period across corners (per unit: ss 3.47 ps /
1292 ps, tt 3.02 / 1045, ff 2.66 / 839 -- 0.27..0.32 % of T) because it is
the same driver and the same cells in both rings; only the tie differs.

custom_cap_4, not the larger custom_cap_16: _16 has a LEF but no Liberty view
in the custom_stdcell library, and _4 is the cell clk_gen already carried
through LibreLane to DRC/LVS clean.

To re-trim, change SLOW_HI / FAST_HI and re-run. dT = (FAST_HI - SLOW_HI) units.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
NBUF = 6          # buf_1 stages after the NAND; the last one drives the caps
NCAP = 8
FAST_HI = 8
SLOW_HI = 2
CAP = "custom_cap_4"

def sch(n_hi, title):
    L = ["v {xschem version=3.4.7 file_version=1.2}", "G {}", "K {}", "V {}",
         "S {}", "E {}"]
    def lab(x, y, net, rot=0, flip=0, name=[0]):
        name[0] += 1
        L.append(f"C {{lab_pin.sym}} {x} {y} {rot} {flip} "
                 f"{{name=l{name[0]} sig_type=std_logic lab={net}}}")
    def cell(sym, x, y, name, rot=0, flip=0, prefix="sg13g2_"):
        L.append(f"C {{{sym}.sym}} {x} {y} {rot} {flip} "
                 f"{{name={name} VDD=VDD VSS=VSS prefix={prefix} }}")
    L.append(f"T {{{title}}} -60 -260 0 0 0.4 0.4 {{}}")
    L.append("T {Generated by gen_osci.py -- edit that, not this file.} "
             "-60 -220 0 0 0.3 0.3 {}")
    # ports
    L.append("C {ipin.sym} -100 -20 0 0 {name=p1 lab=enable}")
    L.append("C {opin.sym} 1300 0 0 0 {name=p2 lab=clk_out}")
    # NAND: A=enable, B=feedback
    cell("sg13g2_nand2_1", 0, 0, "x0")
    L.append("N -100 -20 -60 -20 {lab=enable}")
    lab(-60, 20, f"n{NBUF}")
    lab(60, 0, "n0", 2, 0)
    # buffer chain n0 -> n7
    for i in range(NBUF):
        x = 160 + 120 * i
        cell("sg13g2_buf_1", x, 0, f"x{i+1}")
        lab(x - 40, 0, f"n{i}")
        lab(x + 40, 0, f"n{i+1}", 2, 0)
    # output buffer
    cell("sg13g2_buf_4", 1100, 0, "xo")
    lab(1060, 0, f"n{NBUF}")
    L.append("N 1140 0 1300 0 {lab=clk_out}")
    # trim caps on n7, A to the tie nets
    for c in range(NCAP):
        x = 100 + 100 * c
        cell(CAP, x, 200, f"xc{c}", prefix="custom_")
        lab(x, 230, f"n{NBUF}", 3, 0)
        lab(x - 30, 200, "trim_hi" if c < n_hi else "trim_lo")
    # tie cells -- both rings carry both, so the cell count matches exactly
    cell("sg13g2_tiehi", 0, 400, "xth")
    lab(0, 400, "trim_hi", 2, 0)
    cell("sg13g2_tielo", 200, 400, "xtl")
    lab(200, 400, "trim_lo", 2, 0)
    return "\n".join(L) + "\n"

open(os.path.join(HERE, "fast_osci.sch"), "w").write(
    sch(FAST_HI, f"Fast Vernier ring: {FAST_HI}/{NCAP} trim caps high"))
open(os.path.join(HERE, "slow_osci.sch"), "w").write(
    sch(SLOW_HI, f"Slow Vernier ring: {SLOW_HI}/{NCAP} trim caps high"))
